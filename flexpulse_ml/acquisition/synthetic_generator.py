"""
Synthetic Data Generator for Software Verification in FlexPulse-ML.

SCIENTIFIC INTEGRITY NOTICE:
All records generated by this module are strictly tagged with:
    source_type = "SYNTHETIC_DEMO"
and
    fixture_id = "MOCK_PHYSICS_GENERATOR_SYNTHETIC"

This module exists solely to test software pipelines, algorithms, and visualization
without physical hardware. Synthetic data is NEVER mixed into real experiments.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional
import numpy as np
import pandas as pd

from flexpulse_ml.acquisition.schema import (
    AcquisitionQuality,
    CANONICAL_COLUMNS,
    CableMeasurementRecord,
    CanonicalMeasurementRecord,
    DataProvenance,
    DatasetCategory,
    ElectricalObservation,
    FaultClass,
    FaultOrigin,
    InstrumentCalibration,
    LabelSource,
    MeasurementQuality,
    PhysicalCableIdentity,
    TestConditions,
    TrialSessionIdentity,
)


def generate_canonical_synthetic_dataset(
    cable_ids: Optional[List[str]] = None,
    samples_per_trial: int = 100,
    random_seed: int = 42,
) -> List[CanonicalMeasurementRecord]:
    """Generate deterministic, physics-inspired mock records in the 22-column canonical format.

    Simulates:
    - INTACT: baseline low resistance ~80 mOhm, clean Gaussian thermal noise.
    - RESISTIVE_BEND: resistance spikes when mechanical flex angle increases.
    - INTERMITTENT_DISCONNECT: micro-interruptions with voltage collapse at sink.
    - VBUS_DEGRADATION: elevated path resistance with current-dependent Joule heating.
    - GND_DEGRADATION: elevated resistance with ground-bounce noise.
    """
    rng = np.random.default_rng(random_seed)

    if cable_ids is None:
        cable_ids = [
            "DEMO-CABLE-INTACT-01",
            "DEMO-CABLE-BEND-02",
            "DEMO-CABLE-DISCONN-03",
            "DEMO-CABLE-DEGRAD-04",
        ]

    cable_fault_map = {
        "DEMO-CABLE-INTACT-01": (FaultClass.INTACT.value, "NONE", "STATIC"),
        "DEMO-CABLE-BEND-02": (FaultClass.RESISTIVE_BEND.value, "SERIES_RESISTIVE_BEND_500M", "FLEX_SWEEP_0_90"),
        "DEMO-CABLE-DISCONN-03": (FaultClass.INTERMITTENT_DISCONNECT.value, "PIN_A4_INTERMITTENT", "VIBRATION_SHAKE"),
        "DEMO-CABLE-DEGRAD-04": (FaultClass.VBUS_DEGRADATION.value, "VBUS_TRACE_CORROSION", "THERMAL_LOAD_STEP"),
    }

    records: List[CanonicalMeasurementRecord] = []
    nominal_v = 5.0
    nominal_current = 1.5

    for c_idx, cable_id in enumerate(cable_ids):
        fault_info = cable_fault_map.get(
            cable_id, (FaultClass.INTACT.value, "NONE", "STATIC")
        )
        fault_class_str, fault_cond_str, action_str = fault_info
        session_id = f"SESS-DEMO-{c_idx+1:02d}"
        trial_id = f"TR-DEMO-{c_idx+1:03d}"

        for step in range(samples_per_trial):
            # Monotonic UTC timestamp progression (10ms steps)
            t_iso = datetime.fromtimestamp(1700000000.0 + (step * 0.01), tz=timezone.utc).isoformat()
            flex_angle = float(45.0 * (1.0 + np.sin(2 * np.pi * step / samples_per_trial)))
            r_baseline = 0.080 # 80 mOhm nominal

            is_disconnected = False
            quality_flag = MeasurementQuality.OK.value

            if fault_class_str == FaultClass.INTACT.value:
                r_eff = r_baseline + rng.normal(0.0, 0.002)
            elif fault_class_str == FaultClass.RESISTIVE_BEND.value:
                bend_factor = max(0.0, (flex_angle - 30.0) / 45.0)
                r_eff = r_baseline + (bend_factor * 0.450) + rng.normal(0.0, 0.010)
            elif fault_class_str == FaultClass.INTERMITTENT_DISCONNECT.value:
                is_disconnected = bool(rng.random() < 0.06 and step > 20)
                if is_disconnected:
                    r_eff = 5000.0
                    quality_flag = MeasurementQuality.DISCONNECTED.value
                else:
                    r_eff = r_baseline + rng.normal(0.0, 0.005)
            elif fault_class_str == FaultClass.VBUS_DEGRADATION.value:
                r_eff = 0.420 + rng.normal(0.0, 0.015)
            else:
                r_eff = r_baseline

            v_src = nominal_v + rng.normal(0.0, 0.005)
            if is_disconnected:
                i_meas = 0.0
                v_snk = 0.0
            else:
                i_meas = nominal_current + rng.normal(0.0, 0.008)
                v_drop = i_meas * r_eff
                v_snk = max(0.0, v_src - v_drop)

            record = CanonicalMeasurementRecord(
                timestamp_utc=t_iso,
                cable_id=cable_id,
                session_id=session_id,
                trial_id=trial_id,
                sample_index=step,
                vin_v=round(float(v_src), 4),
                vout_v=round(float(v_snk), 4),
                current_a=round(float(i_meas), 4),
                load_setpoint_a=nominal_current,
                temperature_c=round(25.0 + (step * 0.02), 2),
                source_type=DatasetCategory.SYNTHETIC_DEMO.value,  # MANDATORY DEMO LABEL
                ground_truth_label=fault_class_str,
                ground_truth_source=LabelSource.CONTROLLED_FIXTURE_INJECTION.value,
                fault_origin=FaultOrigin.FIXTURE_INJECTED.value,
                fault_condition=fault_cond_str,
                fixture_id="SYNTHETIC_DEMO_GENERATOR",
                instrument_id="SIMULATED_INA226_CH0",
                calibration_id="CAL_SYNTHETIC_01",
                action_id=action_str,
                motion_region="PLUG_A_STRAIN_RELIEF" if "FLEX" in action_str else "STATIC",
                is_settled=True,
                measurement_quality=quality_flag,
            )
            records.append(record)

    return records


def export_canonical_synthetic_csv(
    output_path: Path,
    cable_ids: Optional[List[str]] = None,
    samples_per_trial: int = 100,
    random_seed: int = 42,
) -> Path:
    """Export synthetic demo dataset adhering strictly to CANONICAL_COLUMNS."""
    records = generate_canonical_synthetic_dataset(
        cable_ids=cable_ids,
        samples_per_trial=samples_per_trial,
        random_seed=random_seed,
    )
    rows = [r.to_dict() for r in records]
    df = pd.DataFrame(rows, columns=list(CANONICAL_COLUMNS))
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    return output_path


def generate_synthetic_cable_dataset(
    cable_ids: Optional[List[str]] = None,
    samples_per_trial: int = 150,
    random_seed: int = 42,
) -> List[CableMeasurementRecord]:
    """Phase 1 backwards-compatible generator returning CableMeasurementRecord objects."""
    canonical_recs = generate_canonical_synthetic_dataset(
        cable_ids=cable_ids,
        samples_per_trial=samples_per_trial,
        random_seed=random_seed,
    )
    return [r.to_cable_measurement_record() for r in canonical_recs]


def export_synthetic_dataset_to_csv(
    output_path: Path,
    cable_ids: Optional[List[str]] = None,
    samples_per_trial: int = 150,
    random_seed: int = 42,
) -> Path:
    """Phase 1 backwards-compatible CSV export."""
    return export_canonical_synthetic_csv(
        output_path=output_path,
        cable_ids=cable_ids,
        samples_per_trial=samples_per_trial,
        random_seed=random_seed,
    )
