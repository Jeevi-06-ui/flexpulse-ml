"""
Synthetic Data Generator for Software Verification in FlexPulse-ML.

SCIENTIFIC INTEGRITY NOTICE:
All records generated by this module are strictly tagged with:
    dataset_category = DatasetCategory.SYNTHETIC_DEMO
and
    source_device = "SYNTHETIC_DEMO_GENERATOR"

This module exists solely to test software pipelines, algorithms, and visualization
without physical hardware. Synthetic data is NEVER mixed into real experiments.
"""

from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional
import numpy as np
import pandas as pd

from flexpulse_ml.acquisition.schema import (
    AcquisitionQuality,
    CableMeasurementRecord,
    DataProvenance,
    DatasetCategory,
    ElectricalObservation,
    FaultClass,
    FaultOrigin,
    InstrumentCalibration,
    LabelSource,
    PhysicalCableIdentity,
    TestConditions,
    TrialSessionIdentity,
)


def generate_synthetic_cable_dataset(
    cable_ids: Optional[List[str]] = None,
    samples_per_trial: int = 150,
    random_seed: int = 42,
) -> List[CableMeasurementRecord]:
    """Generate deterministic, physics-inspired mock records for software testing.

    Simulates:
    - INTACT: baseline low resistance ~80 mOhm, clean Gaussian thermal noise.
    - RESISTIVE_BEND: resistance spikes when mechanical flex angle increases.
    - INTERMITTENT_DISCONNECT: micro-interruptions with voltage collapse at sink.
    - VBUS_DEGRADATION: elevated path resistance with current-dependent Joule heating.
    - GND_DEGRADATION: elevated resistance with ground-bounce noise.
    """
    rng = np.random.default_rng(random_seed)

    if cable_ids is None:
        cable_ids = [
            "DEMO-CABLE-INTACT-01",
            "DEMO-CABLE-BEND-02",
            "DEMO-CABLE-DISCONN-03",
            "DEMO-CABLE-DEGRAD-04",
        ]

    # Assign a specific condition profile to each demo cable
    cable_fault_map = {
        "DEMO-CABLE-INTACT-01": FaultClass.INTACT,
        "DEMO-CABLE-BEND-02": FaultClass.RESISTIVE_BEND,
        "DEMO-CABLE-DISCONN-03": FaultClass.INTERMITTENT_DISCONNECT,
        "DEMO-CABLE-DEGRAD-04": FaultClass.VBUS_DEGRADATION,
    }

    records: List[CableMeasurementRecord] = []
    nominal_v = 5.0
    nominal_current = 1.5

    for c_idx, cable_id in enumerate(cable_ids):
        fault = cable_fault_map.get(cable_id, FaultClass.INTACT)
        session_id = f"SESS-DEMO-{c_idx+1:02d}"
        trial_id = f"TR-DEMO-{c_idx+1:03d}"

        cable_spec = PhysicalCableIdentity(
            cable_id=cable_id,
            manufacturer="DEMO_CABLE_CORP",
            cable_type="USB_C_TO_C",
            rated_current_a=3.0,
            rated_length_m=1.0,
            has_emask_chip=False,
        )

        for step in range(samples_per_trial):
            t_ms = float(step * 10.0) # 100 Hz sampling (10ms interval)
            jitter_us = float(rng.normal(0.0, 15.0))

            # Simulate dynamic flex angle sweep (0 deg to 90 deg and back)
            flex_angle = float(45.0 * (1.0 + np.sin(2 * np.pi * step / samples_per_trial)))

            # Physics-based baseline cable resistance calculation (Ohms)
            r_baseline = 0.080 # 80 mOhm normal copper conductor + contact

            if fault == FaultClass.INTACT:
                r_eff = r_baseline + rng.normal(0.0, 0.002)
                is_disconnected = False
            elif fault == FaultClass.RESISTIVE_BEND:
                # Contact opens partially as flex angle increases beyond 45 degrees
                bend_factor = max(0.0, (flex_angle - 30.0) / 45.0)
                r_eff = r_baseline + (bend_factor * 0.450) + rng.normal(0.0, 0.010)
                is_disconnected = False
            elif fault == FaultClass.INTERMITTENT_DISCONNECT:
                # Random sporadic micro-disconnections (5% probability)
                is_disconnected = bool(rng.random() < 0.06 and step > 20)
                r_eff = 5000.0 if is_disconnected else (r_baseline + rng.normal(0.0, 0.005))
            elif fault == FaultClass.VBUS_DEGRADATION:
                # Heavily corroded/damaged VBUS conductor
                r_eff = 0.420 + rng.normal(0.0, 0.015)
                is_disconnected = False
            else:
                r_eff = r_baseline
                is_disconnected = False

            # Calculate electrical values
            v_src = nominal_v + rng.normal(0.0, 0.005) # Small source ripple
            if is_disconnected:
                i_meas = 0.0
                v_snk = 0.0
            else:
                i_meas = nominal_current + rng.normal(0.0, 0.008)
                v_drop = i_meas * r_eff
                v_snk = max(0.0, v_src - v_drop)

            conditions = TestConditions(
                nominal_voltage_v=nominal_v,
                target_current_a=nominal_current,
                ambient_temp_c=25.0 + (step * 0.02), # Slight thermal rise
                flex_angle_deg=flex_angle,
                mechanical_state="BENDING_SWEEP" if flex_angle > 5.0 else "STATIC",
            )

            observation = ElectricalObservation(
                v_source_v=round(float(v_src), 4),
                v_sink_v=round(float(v_snk), 4),
                current_a=round(float(i_meas), 4),
                timestamp_rel_ms=round(t_ms, 2),
                sampling_jitter_us=round(jitter_us, 1),
            )

            provenance = DataProvenance(
                source_device="SYNTHETIC_DEMO_GENERATOR",
                firmware_version="0.1.0-sim",
                operator_id="SIMULATED_TEST_RUNNER",
                git_commit_hash="DEMO_HASH",
                recorded_at_utc=datetime.now(timezone.utc).isoformat(),
            )

            calibration = InstrumentCalibration(
                fixture_tare_resistance_ohms=0.040,
                v_offset_v=0.0,
                i_offset_a=0.0,
            )

            quality = AcquisitionQuality(
                sample_rate_hz=100.0,
                dropped_samples_count=0,
                is_clipped=False,
                adc_settled=True,
            )

            record = CableMeasurementRecord(
                cable=cable_spec,
                session=TrialSessionIdentity(session_id=session_id, trial_id=trial_id, step_index=step),
                conditions=conditions,
                observation=observation,
                ground_truth=fault,
                label_source=LabelSource.CONTROLLED_FIXTURE_INJECTION,
                fault_origin=FaultOrigin.FIXTURE_INJECTED,
                provenance=provenance,
                calibration=calibration,
                quality=quality,
                dataset_category=DatasetCategory.SYNTHETIC_DEMO, # MANDATORY LABELLING
            )
            records.append(record)

    return records


def export_synthetic_dataset_to_csv(
    output_path: Path,
    cable_ids: Optional[List[str]] = None,
    samples_per_trial: int = 150,
    random_seed: int = 42,
) -> Path:
    """Generate and write a synthetic demo dataset to CSV."""
    records = generate_synthetic_cable_dataset(
        cable_ids=cable_ids,
        samples_per_trial=samples_per_trial,
        random_seed=random_seed,
    )
    flat_rows = [r.to_flat_dict() for r in records]
    df = pd.DataFrame(flat_rows)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    return output_path
